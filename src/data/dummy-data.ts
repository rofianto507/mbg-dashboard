function generateDailyData(): DailyData[] {
  const data: DailyData[] = [];
  const now = new Date('2024-01-15');

  for (let i = 29; i >= 0; i--) {
    const date = new Date(now);
    date.setDate(date.getDate() - i);
    const dayOfWeek = date.getDay();
    const isWeekend = dayOfWeek === 0 || dayOfWeek === 6;

    const basePortions = isWeekend ? 8500000 : 12500000;
    const variance = (Math.random() - 0.5) * 800000;
    const distributed = Math.round(basePortions + variance);

    const baseTarget = isWeekend ? 9000000 : 13000000;
    const target = Math.round(baseTarget + (Math.random() - 0.5) * 200000);

    const nutritionScore = Math.round(78 + (Math.random() - 0.5) * 8);
    const budget = Math.round(distributed * 15200 / 1000000);

    data.push({
      date: date.toISOString().split('T')[0],
      distributed,
      target,
      nutritionScore,
      budget,
    });
  }

  return data;
}

